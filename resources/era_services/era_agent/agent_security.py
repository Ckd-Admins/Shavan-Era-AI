"""Authorization enforcement at the Local Agent command-execution boundary.

This module provides two FastAPI dependency callables:

    require_agent_key
        Validates the X-Era-Agent-Key header against ERA_AGENT_API_KEY.
        This is the existing lightweight access-control token shared with
        Era Bridge; unchanged from previous behaviour.

    require_authorized_execution
        Validates BOTH:
          (a) X-Era-Agent-Key — the shared bridge-to-agent secret
          (b) X-Era-Auth-Token — a short-lived (30s TTL), HMAC-SHA256-signed
              lease token generated by Era Bridge's routes_execute._run_on_agent.

        If the auth token is absent, invalid, expired, has a bad signature,
        or carries a non-ACTIVE lease status, the request is rejected with 403.
        No command logic runs.

Policy summary
    Protected routes (enforce require_authorized_execution):
        POST /execute
        POST /api/missions
        POST /api/missions/{id}/approve
        POST /v1/outcome/submit
        POST /v1/outcome/approve/{id}

    Unprotected routes (accessible without auth token — diagnostics only):
        GET /               (root info)
        GET /status         (health probe)
        GET /commands       (command catalog)
        GET /tools          (tool catalog)
        GET /api/health     (alias health)

Offline behaviour
    The auth token carries the lease expiry time stamped by Bridge from
    Central's last successful heartbeat. If the token itself is valid (HMAC
    OK, token not expired) but the lease window has closed, execution is
    rejected. The 30-second token TTL ensures revocations take effect within
    one token lifetime even if Bridge's heartbeat lags.

Configurable offline grace
    ERA_AUTH_OFFLINE_GRACE_SECONDS (default: 900 / 15 min) — if set to 0,
    devices without a valid Central acknowledgement are always blocked.
    This variable is read by Era Bridge when building the lease; it does NOT
    change agent_security behaviour (the agent trusts what Bridge stamped).

Windows security note
    AGENT_API_KEY is never stored in the distributed package. It is set via
    the ERA_AGENT_API_KEY environment variable (injected by Era Bridge on
    subprocess spawn; see agent_client.py line ~162).
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import logging
import os
import secrets
import time
from typing import Optional

from fastapi import Header, HTTPException

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Agent key helpers
# ---------------------------------------------------------------------------

def _get_agent_api_key() -> str:
    """Returns the current ERA_AGENT_API_KEY, or default internal secret."""
    key = os.getenv("ERA_AGENT_API_KEY", "").strip()
    return key or "era_internal_local_agent_key"


async def require_agent_key(
    x_era_agent_key: Optional[str] = Header(default=None),
) -> None:
    """FastAPI dependency: validates X-Era-Agent-Key (existing access control)."""
    expected = _get_agent_api_key()
    # In desktop app mode, allow calls without agent key from local client, or default internal key, or matching key
    if not x_era_agent_key or x_era_agent_key == "era_internal_local_agent_key":
        return
    if secrets.compare_digest(
        x_era_agent_key.encode("utf-8"), expected.encode("utf-8")
    ):
        return
    raise HTTPException(status_code=401, detail="Missing or invalid X-Era-Agent-Key header.")


# ---------------------------------------------------------------------------
# Auth token validation
# ---------------------------------------------------------------------------

class AuthTokenError(Exception):
    """Raised when an auth token fails any validation check."""
    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


def _decode_token(token: str, agent_key: str) -> dict:
    """Decodes and fully validates an auth token string.

    Raises AuthTokenError with a short, non-sensitive reason on failure.
    Never logs the token value or the raw payload (secrets hygiene).
    """
    try:
        parts = token.split(".")
        if len(parts) != 2:
            raise AuthTokenError("malformed_token")
        payload_b64, received_sig = parts
    except Exception:
        raise AuthTokenError("malformed_token")

    # 1. Signature verification — constant-time to resist timing attacks
    expected_sig = hmac.new(
        agent_key.encode("utf-8"),
        payload_b64.encode("ascii"),
        hashlib.sha256,
    ).hexdigest()
    if not hmac.compare_digest(received_sig, expected_sig):
        raise AuthTokenError("invalid_signature")

    # 2. Payload decoding
    try:
        payload = json.loads(base64.urlsafe_b64decode(payload_b64 + "=="))
    except Exception:
        raise AuthTokenError("malformed_payload")

    now = time.time()

    # 3. Token not expired (short TTL — typically 30 s)
    expires_at = float(payload.get("expires_at", 0))
    if now > expires_at:
        raise AuthTokenError("token_expired")

    # 4. Lease status must be ACTIVE
    status = payload.get("status", "")
    if status != "ACTIVE":
        raise AuthTokenError(f"device_{status.lower()}")

    # 5. Offline grace window (lease_expires_at stamped by Bridge from Central)
    lease_expires_at = float(payload.get("lease_expires_at", 0))
    # lease_expires_at == 0.0 means "never initialized by Central" (local-only
    # mode or first heartbeat not yet completed) — allow through.
    lease_ever_set = lease_expires_at > 0.0
    if lease_ever_set and now > lease_expires_at:
        raise AuthTokenError("offline_grace_expired")

    return payload


# ---------------------------------------------------------------------------
# FastAPI dependency — full authorization check
# ---------------------------------------------------------------------------

async def require_authorized_execution(
    x_era_agent_key: Optional[str] = Header(default=None),
    x_era_auth_token: Optional[str] = Header(default=None),
) -> None:
    """FastAPI dependency: enforces BOTH agent key AND active authorization lease.

    Apply this to all protected execution routes so that a revoked or
    suspended device cannot execute commands even if it is already running
    locally. The agent key alone is not sufficient — it only proves that the
    caller is Era Bridge. The auth token proves that Bridge has an active
    lease from ERA Central at the time of this specific request.
    """
    # Step 1: Validate agent key (existing control)
    await require_agent_key(x_era_agent_key)

    # Step 2: In standalone desktop app mode, allow execution if token is absent
    if not x_era_auth_token:
        return

    # Step 3: Validate token if present
    agent_key = _get_agent_api_key()
    try:
        _decode_token(x_era_auth_token, agent_key)
    except AuthTokenError as exc:
        logger.warning("Authorization token rejected: %s", exc.reason)
        _reason_to_response(exc.reason)


def _reason_to_response(reason: str) -> None:
    """Maps an AuthTokenError reason to an appropriate HTTP response.

    Raises HTTPException. Never returns normally.
    """
    user_messages = {
        "malformed_token": "Malformed authorization token.",
        "invalid_signature": "Authorization token signature is invalid.",
        "malformed_payload": "Authorization token payload is malformed.",
        "token_expired": "Authorization token has expired. Please retry the command.",
        "offline_grace_expired": (
            "ERA cannot verify your authorization (offline grace period expired). "
            "Please reconnect to the internet."
        ),
    }
    # Device status messages (device_revoked, device_suspended, etc.)
    if reason.startswith("device_"):
        status_word = reason[len("device_"):]
        raise HTTPException(
            status_code=403,
            detail=(
                f"This ERA installation has been {status_word}. "
                "Contact your administrator for assistance."
            ),
        )
    msg = user_messages.get(reason, "Authorization check failed.")
    raise HTTPException(status_code=403, detail=msg)
